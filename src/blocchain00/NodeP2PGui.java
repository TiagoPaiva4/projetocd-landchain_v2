    private void btStartServerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btStartServerActionPerformed
        try {
            int port = Integer.parseInt(txtServerListeningPort.getText());
            myRemote = new RemoteNodeObject(port, this);
            RMI.startRemoteObject(myRemote, port, RemoteNodeObject.OBJECT_NAME);
            
        } catch (Exception ex) {
            System.getLogger(NodeP2PGui.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            onException(ex, "Start Server");
        }

    }//GEN-LAST:event_btStartServerActionPerformed

