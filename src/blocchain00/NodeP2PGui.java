    @Override
    public void onStart(String message) {
        SwingUtilities.invokeLater(() -> {
            btStartServer.setEnabled(false);
            imgServerRunning.setEnabled(true);
            txtServerListeningPort.setEnabled(false);
            GuiUtils.addText(txtServerLog, "Runnig", "Server");
            try {
                this.setTitle(myRemote.getAdress());
                txtNodeAddress.setText(myRemote.getAdress());
            } catch (RemoteException ex) {
                System.getLogger(NodeP2PGui.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
                onException(ex, "Start server");
            }
            
        });
    }
    
    @Override
    public void onException(Exception e, String title) {
        SwingUtilities.invokeLater(() -> {
            GuiUtils.addText(txtServerLog, title, e.getMessage());
            tpMain.setSelectedComponent(pnServer);
        });
        
    }
    
    @Override
    public void onConect(String address) {
        SwingUtilities.invokeLater(() -> {
            try {
                String nodes = "";
                for (RemoteNodeInterface node : myRemote.getNetwork()) {
                    nodes += node.getAdress() + "\n";
                }
                txtNetwork.setText(nodes);
                tpMain.setSelectedComponent(pnNetwork);
            } catch (RemoteException ex) {
                System.getLogger(NodeP2PGui.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
                onException(ex, "Connect");
            }
            
        });
        
    }
    
